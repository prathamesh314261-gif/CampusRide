"""
Payment routes — 100% SQL-Driven.
Payment processing via sp_process_payment() stored procedure.
Payment history via vw_payment_history VIEW.
"""
from fastapi import APIRouter, Depends, HTTPException, Form
from sqlalchemy.orm import Session
from sqlalchemy import text
from typing import Optional
import auth
from database import get_db

router = APIRouter(prefix="/api/payments", tags=["payments"])


@router.post("")
def make_payment(
    rental_id:      int = Form(...),
    payment_method: str = Form("UPI"),
    token: str = Depends(auth.oauth2_scheme),
    db: Session = Depends(get_db)
):
    """
    100% SQL-Driven Payment.
    Calls sp_process_payment() — transaction ID generated by MySQL fn_generate_txn_id().
    MySQL TRIGGER trg_after_payment_insert auto-logs the payment in AuditLog.
    """
    payload = auth.verify_token(token)
    user_id = int(payload.get("sub"))

    # Verify this rental belongs to this user
    rental = db.execute(
        text("SELECT * FROM Rental WHERE rental_id = :rid AND student_id = :uid"),
        {"rid": rental_id, "uid": user_id}
    ).fetchone()
    if not rental:
        raise HTTPException(status_code=404, detail="Rental not found")

    # Validate payment method
    allowed_methods = ("UPI", "Card", "Cash")
    if payment_method not in allowed_methods:
        payment_method = "UPI"

    # ✅ Call MySQL Stored Procedure — transaction ID and amount fetched from DB
    db.execute(text("SET @p_txn_id = '', @p_status = ''"))
    db.execute(
        text("CALL sp_process_payment(:rid, :method, @p_txn_id, @p_status)"),
        {"rid": rental_id, "method": payment_method}
    )

    result = db.execute(text("SELECT @p_txn_id AS txn_id, @p_status AS status")).fetchone()
    sp_status = result._mapping["status"]
    txn_id    = result._mapping["txn_id"]
    db.commit()

    if sp_status == "ALREADY_PAID":
        raise HTTPException(status_code=400, detail="Payment already completed for this rental")
    elif sp_status != "OK":
        raise HTTPException(status_code=500, detail="Payment processing failed")

    return {
        "message":        "Payment successful!",
        "transaction_id": txn_id,
        "amount":         float(rental._mapping["final_amount"]),
        "method":         payment_method
    }


@router.get("/my")
def get_my_payments(token: str = Depends(auth.oauth2_scheme), db: Session = Depends(get_db)):
    """
    Get payment history for current student.
    ✅ Queries vw_payment_history VIEW directly.
    """
    payload = auth.verify_token(token)
    user_id = int(payload.get("sub"))

    rows = db.execute(
        text("SELECT * FROM vw_payment_history WHERE student_id = :uid ORDER BY payment_id DESC"),
        {"uid": user_id}
    ).fetchall()
    return [dict(zip(r._mapping.keys(), r._mapping.values())) for r in rows]


@router.get("/{payment_id}/receipt")
@router.get("/receipt/{payment_id}")
def get_receipt(payment_id: int, token: str = Depends(auth.oauth2_scheme), db: Session = Depends(get_db)):
    """Get a single payment receipt with full details — raw SQL JOIN."""
    payload = auth.verify_token(token)
    user_id = int(payload.get("sub"))

    row = db.execute(
        text("""
            SELECT p.*,
                   CONCAT('RCP-', LPAD(p.payment_id, 5, '0')) AS receipt_no,
                   p.amount AS amount_paid,
                   r.start_time, r.end_time, r.total_hours,
                   r.total_hours AS rental_hours,
                   r.subtotal, r.discount, r.final_amount,
                   CONCAT(v.brand, ' ', v.model) AS vehicle_name,
                   v.license_plate, v.vehicle_type,
                   s.full_name AS student_name, s.roll_number
            FROM Payment p
            JOIN Rental r  ON p.rental_id = r.rental_id
            JOIN Vehicle v ON r.vehicle_id = v.vehicle_id
            JOIN Student s ON r.student_id = s.student_id
            WHERE p.payment_id = :pid AND r.student_id = :uid
        """),
        {"pid": payment_id, "uid": user_id}
    ).fetchone()

    if not row:
        raise HTTPException(status_code=404, detail="Receipt not found")
    return dict(zip(row._mapping.keys(), row._mapping.values()))